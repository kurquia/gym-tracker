#!/usr/bin/env bash
# Builds the launcher-icon and splash PNGs from assets/icon/atlas.svg.
# "Atlas" by Delapouite (https://game-icons.net), CC BY 3.0.
# Needs rsvg-convert. Afterwards run:
#   dart run flutter_launcher_icons && dart run flutter_native_splash:create
set -euo pipefail
cd "$(dirname "$0")/../assets/icon"

# The SVG is a black square plus one white figure path; keep only the figure.
figure=$(grep -o '<path fill="#fff"[^>]*/>' atlas.svg)

# render <out.png> <size px> <scale of figure> <background: black|none>
render() {
  local out=$1 size=$2 scale=$3 bg=$4
  local offset; offset=$(python3 -c "print(256 * (1 - $scale))")
  local rect=""; [[ $bg == black ]] && rect='<rect width="512" height="512"/>'
  printf '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">%s<g transform="translate(%s %s) scale(%s)">%s</g></svg>' \
    "$rect" "$offset" "$offset" "$scale" "$figure" |
    rsvg-convert -w "$size" -h "$size" -o "$out"
}

# Legacy square icon (pre-Android 8 launchers).
render icon.png 1024 0.80 black
# Adaptive foreground: launchers crop to the central ~61%, so keep it small.
render icon_foreground.png 1024 0.52 none
# Android 12+ splash: shown inside a circle of 2/3 the image size.
render splash_android12.png 1152 0.52 none
# Older-Android splash: figure only, drawn centered.
render splash.png 768 0.90 none

# Status-bar icon for the workout notification: white figure, transparent
# background, as an Android vector drawable (the SVG path data works as is).
d=$(grep -o '<path fill="#fff" d="[^"]*"' atlas.svg | sed 's/.* d="//; s/"$//')
cat > ../../android/app/src/main/res/drawable/ic_stat_workout.xml <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- "Atlas" by Delapouite (game-icons.net), CC BY 3.0. Generated by tool/make_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="512" android:viewportHeight="512">
  <path android:fillColor="#FFFFFFFF" android:pathData="$d"/>
</vector>
XML
